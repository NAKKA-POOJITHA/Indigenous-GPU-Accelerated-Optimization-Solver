def solve_with_hunters(lp_path: str) -> Dict[str, Any]:
    solver = HuntersSolver()
    opts = SolverOptions(presolve=True, scaling=True, verbose=False)
    t0 = time.perf_counter()
    res = solver.solve_file(lp_path, opts)
    t_elapsed = time.perf_counter() - t0

    return {
        "solver": "Hunters Solver (Sovereign Core)",
        "status": res.status,
        "objective": res.objective,
        "best_bound": res.best_bound,
        "mip_gap": res.mip_gap,
        "runtime_ms": max(res.solve_time_sec * 1000.0, t_elapsed * 1000.0),
        "nodes": res.node_count,
        "lp_iter": res.lp_iterations,
        "valid": res.validation.is_valid if res.validation else True,
        "max_residual": res.validation.max_primal_residual if res.validation else 0.0,
    }


